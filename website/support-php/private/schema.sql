
CREATE TABLE IF NOT EXISTS users (
 id TEXT PRIMARY KEY, discord_name TEXT NOT NULL, ign TEXT NOT NULL DEFAULT '',
 rank TEXT NOT NULL DEFAULT 'Member', color INTEGER NOT NULL DEFAULT 0,
 staff INTEGER NOT NULL DEFAULT 0, checked REAL NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS sessions (
 token TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id), csrf TEXT NOT NULL, expires REAL NOT NULL
);
CREATE TABLE IF NOT EXISTS oauth (
 state TEXT PRIMARY KEY, verifier TEXT NOT NULL, expires REAL NOT NULL
);
CREATE TABLE IF NOT EXISTS tickets (
 id TEXT PRIMARY KEY, creator TEXT NOT NULL REFERENCES users(id), category TEXT NOT NULL,
 subject TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'open', created REAL NOT NULL,
 updated REAL NOT NULL, closed REAL, reason TEXT NOT NULL DEFAULT '', media_url TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS messages (
 id INTEGER PRIMARY KEY AUTOINCREMENT, ticket_id TEXT NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
 author TEXT NOT NULL, ign TEXT NOT NULL, discord_name TEXT NOT NULL, rank TEXT NOT NULL, color INTEGER NOT NULL,
 kind TEXT NOT NULL DEFAULT 'message', body TEXT NOT NULL, created REAL NOT NULL
);
CREATE INDEX IF NOT EXISTS message_ticket ON messages(ticket_id,id);
CREATE INDEX IF NOT EXISTS ticket_creator ON tickets(creator,updated);
CREATE TABLE IF NOT EXISTS attachments (
 id TEXT PRIMARY KEY, message_id INTEGER NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
 ticket_id TEXT NOT NULL REFERENCES tickets(id) ON DELETE CASCADE, name TEXT NOT NULL,
 stored TEXT NOT NULL, mime TEXT NOT NULL, size INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS outbox (
 id TEXT PRIMARY KEY REFERENCES tickets(id) ON DELETE CASCADE,
 attempts INTEGER NOT NULL DEFAULT 0, next_try REAL NOT NULL DEFAULT 0, sent REAL,
 last_status INTEGER
);
CREATE TABLE IF NOT EXISTS limits (bucket TEXT NOT NULL, happened REAL NOT NULL);
CREATE INDEX IF NOT EXISTS limits_bucket ON limits(bucket,happened);
